export function CatalogVideoWizard({
  onClose,
  onCreated,
}: {
  onClose: () => void;
  onCreated: () => void;
}): React.ReactElement {
  const qc = useQueryClient();
  const [step, setStep] = useState<1 | 2 | 3>(1);
  const [sourceTab, setSourceTab] = useState<'existing' | 'upload'>('existing');
  const [source, setSource] = useState<ImageSource | null>(null);
  const [sampleVideoId, setSampleVideoId] = useState<string | null>(null);
  const [submitting, setSubmitting] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [uploading, setUploading] = useState(false);
  const [uploadProgress, setUploadProgress] = useState(0);
  const [uploadError, setUploadError] = useState<string | null>(null);
  const uploadAbortRef = useRef<AbortController | null>(null);

  // Revoke the previous upload's blob URL whenever `source` changes away from
  // it (a new upload, switching to an existing-image selection, or unmount) —
  // never the currently active one.
  useEffect(() => {
    return () => {
      if (source?.kind === 'upload') URL.revokeObjectURL(source.previewUrl);
    };
  }, [source]);

  const { data: catalogues, isLoading: cataloguesLoading } = useQuery<CatalogueResponse>({
    queryKey: ['catalogues'],
    queryFn: () => api.get('/v1/catalogues'),
  });

  const { data: sampleVideos, isLoading: sampleVideosLoading } = useQuery<{
    creditCost: number;
    items: SampleVideoOption[];
  }>({
    queryKey: ['sample-videos'],
    queryFn: () => api.get('/v1/models/sample-videos'),
    enabled: step >= 2,
  });

  const { data: creditsData } = useQuery<{ balance: number }>({
    queryKey: ['credits'],
    queryFn: () => api.get('/v1/credits'),
    enabled: step >= 2,
  });

  const creditCost = sampleVideos?.creditCost;
  const balance = creditsData?.balance;
  const insufficientCredits =
    typeof creditCost === 'number' && typeof balance === 'number' && balance < creditCost;

  const imageOptions: CatalogueImageOption[] = (catalogues ?? []).flatMap((catalogue) =>
    catalogue.jobs
      .filter((job) => job.status === 'COMPLETED')
      .map((job) => ({
        jobId: job.id,
        catalogueId: catalogue.catalogueId,
      })),
  );
  const selectedSample = sampleVideos?.items.find((option) => option.id === sampleVideoId);

  async function handleUpload(file: File) {
    if (uploading) return;
    if (file.size > 10 * 1024 * 1024) {
      setUploadError('File exceeds 10 MB. Please choose a smaller image.');
      return;
    }
    if (!(await isSupportedImageBytes(file))) {
      setUploadError('Unsupported file type. Please upload a JPEG, PNG, or WebP image.');
      return;
    }
    setUploadError(null);
    setUploading(true);
    setUploadProgress(0);
    const abort = new AbortController();
    uploadAbortRef.current = abort;
    const previewUrl = URL.createObjectURL(file);
    try {
      const { uploadUrl, r2Key } = await api.post<{
        uploadUrl: string;
        r2Key: string;
        expiresIn: number;
      }>('/v1/uploads/presign', { contentType: file.type, contentLength: file.size });
      await api.uploadToR2WithProgress(uploadUrl, file, setUploadProgress, abort.signal);
      setSource({ kind: 'upload', r2Key, previewUrl });
    } catch (e) {
      URL.revokeObjectURL(previewUrl);
      if (e instanceof DOMException && e.name === 'AbortError') return;
      const msg = e instanceof Error ? e.message : '';
      setUploadError(
        msg.includes('403')
          ? 'Upload session expired. Please re-upload your image and try again.'
          : `Upload failed: ${msg}`,
      );
    } finally {
      setUploading(false);
    }
  }

  function handleClose() {
    if (submitting) return;
    uploadAbortRef.current?.abort();
    onClose();
  }

  const handleSubmit = async () => {
    if (!source || !sampleVideoId || insufficientCredits) return;
    setSubmitting(true);
    setError(null);
    try {
      await api.post('/v1/jobs/catalog-video', {
        ...(source.kind === 'existing'
          ? { sourceJobId: source.jobId }
          : { sourceImageKey: source.r2Key }),
        sampleVideoId,
      });
      await qc.invalidateQueries({ queryKey: ['catalog-videos'] });
      onCreated();
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Failed to start video generation');
    } finally {
      setSubmitting(false);
    }
  };

  const nextDisabled =
    (step === 1 && !source) || (step === 2 && !sampleVideoId) || submitting || uploading;

  return (
    <>
      <style>{`
        .wizard-backdrop {
          position: fixed;
          inset: 0;
          z-index: 1000;
          display: flex;
          align-items: center;
          justify-content: center;
          padding: 20px;
          background: rgba(8, 12, 24, 0.62);
        }

        .wizard-dialog {
          width: min(960px, calc(100vw - 40px));
          height: min(800px, calc(100vh - 40px));
          overflow: hidden;
          border: 1px solid ${C.border};
          border-radius: 8px;
          background: ${C.card};
          box-shadow: 0 20px 56px rgba(0, 0, 0, 0.32);
          display: flex;
          flex-direction: column;
        }

        .wizard-step1-grid {
          display: grid;
          grid-template-columns: repeat(auto-fill, minmax(150px, 1fr));
          gap: 12px;
        }

        .wizard-step2-grid {
          display: grid;
          grid-template-columns: repeat(auto-fill, minmax(240px, 1fr));
          gap: 16px;
        }

        .wizard-step3-grid {
          display: grid;
          grid-template-columns: 1fr 1fr;
          gap: 16px;
        }

        @media (max-width: 639px) {
          .wizard-backdrop {
            padding: 10px;
          }
          .wizard-dialog {
            width: calc(100vw - 20px);
            height: calc(100vh - 20px);
          }
          .wizard-step1-grid {
            grid-template-columns: repeat(2, 1fr);
            gap: 10px;
          }
          .wizard-step2-grid {
            grid-template-columns: repeat(2, 1fr);
            gap: 10px;
          }
          .wizard-step3-grid {
            grid-template-columns: 1fr;
            gap: 12px;
          }
        }
      `}</style>
      {/* biome-ignore lint/a11y/noStaticElementInteractions: modal backdrop; click outside dismisses */}
      <div
        role="presentation"
        className="wizard-backdrop"
        onMouseDown={(event) => {
          if (event.target === event.currentTarget) handleClose();
        }}
      >
        <section
          role="dialog"
          aria-modal="true"
          aria-labelledby="catalog-video-wizard-title"
          className="wizard-dialog"
        >
          <header
            style={{
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'space-between',
              gap: 16,
              padding: '18px 20px',
              borderBottom: `1px solid ${C.border}`,
            }}
          >
            <div>
              <h2
                id="catalog-video-wizard-title"
                style={{ margin: 0, color: C.text, fontSize: 18 }}
              >
                New Catalog Video
              </h2>
              {/* biome-ignore lint/a11y/useSemanticElements: decorative step indicator, not a form control group — <fieldset> would misrepresent it */}
              <div
                role="group"
                style={{ display: 'flex', gap: 6, marginTop: 10 }}
                aria-label={`Step ${step} of 3`}
              >
                {[1, 2, 3].map((item) => (
                  <span
                    key={item}
                    style={{
                      display: 'block',
                      width: 42,
                      height: 3,
                      background: item <= step ? C.pink : C.border,
                    }}
                  />
                ))}
              </div>
            </div>
            <button
              type="button"
              aria-label="Close"
              disabled={submitting}
              onClick={handleClose}
              style={{
                width: 32,
                height: 32,
                border: `1px solid ${C.border}`,
                borderRadius: 6,
                background: 'transparent',
                color: C.mid,
                display: 'grid',
                placeItems: 'center',
                cursor: submitting ? 'not-allowed' : 'pointer',
              }}
            >
              <X size={16} />
            </button>
          </header>

          <div style={{ padding: 20, overflowY: 'auto', flex: 1, minHeight: 0 }}>
            {step === 1 && (
              <>
                <div style={{ display: 'flex', gap: 8, marginBottom: 16 }}>
                  {(['existing', 'upload'] as const).map((tab) => (
                    <button
                      key={tab}
                      type="button"
                      aria-pressed={sourceTab === tab}
                      onClick={() => setSourceTab(tab)}
                      style={{
                        padding: '8px 16px',
                        borderRadius: 999,
                        border: `1px solid ${sourceTab === tab ? C.pink : C.border}`,
                        background: sourceTab === tab ? 'rgba(245,92,122,0.08)' : 'transparent',
                        color: sourceTab === tab ? C.pink : C.mid,
                        fontSize: 13,
                        fontWeight: 600,
                        cursor: 'pointer',
                      }}
                    >
                      {tab === 'existing' ? 'My Catalogue Images' : 'Upload New'}
                    </button>
                  ))}
                </div>

                {sourceTab === 'existing' ? (
                  <>
                    <p style={{ margin: '0 0 16px', color: C.mid, fontSize: 13 }}>
                      Choose a completed catalogue image.
                    </p>
                    {cataloguesLoading ? (
                      <p style={{ color: C.mid, fontSize: 13 }}>Loading images...</p>
                    ) : imageOptions.length === 0 ? (
                      <p style={{ color: C.mid, fontSize: 13 }}>
                        No completed catalogue images are available.
                      </p>
                    ) : (
                      <div className="wizard-step1-grid">
                        {imageOptions.map((option) => {
                          const selected =
                            source?.kind === 'existing' && source.jobId === option.jobId;
                          return (
                            <button
                              key={option.jobId}
                              type="button"
                              aria-pressed={selected}
                              onClick={() => setSource({ kind: 'existing', jobId: option.jobId })}
                              style={{
                                position: 'relative',
                                aspectRatio: '3 / 4',
                                overflow: 'hidden',
                                border: selected ? `2px solid ${C.pink}` : `1px solid ${C.border}`,
                                borderRadius: 6,
                                padding: 0,
                                background: C.lighter,
                                cursor: 'pointer',
                              }}
                            >
                              <JobThumbnail jobId={option.jobId} alt="" />
                              {selected && (
                                <span
                                  style={{
                                    position: 'absolute',
                                    top: 8,
                                    right: 8,
                                    width: 22,
                                    height: 22,
                                    borderRadius: 999,
                                    background: C.pink,
                                    color: C.white,
                                    display: 'grid',
                                    placeItems: 'center',
                                  }}
                                >
                                  <Check size={14} />
                                </span>
                              )}
                            </button>
                          );
                        })}
                      </div>
                    )}
                  </>
                ) : (
                  <>
                    <p style={{ margin: '0 0 16px', color: C.mid, fontSize: 13 }}>
                      Upload any photo you own — it doesn't need to be an AI Vastra generation.
                    </p>
                    <div style={{ display: 'flex', gap: 20, flexWrap: 'wrap' }}>
                      <UploadDropzone
                        onFile={handleUpload}
                        onRemove={() => setSource(null)}
                        uploading={uploading}
                        progress={uploadProgress}
                        error={uploadError}
                        previewUrl={source?.kind === 'upload' ? source.previewUrl : null}
                      />
                      <UploadTips />
                    </div>
                  </>
                )}
              </>
            )}

            {step === 2 && (
              <>
                <p style={{ margin: '0 0 8px', color: C.mid, fontSize: 13 }}>
                  Choose the motion template for your video.
                </p>
                {typeof creditCost === 'number' && (
                  <p
                    style={{
                      margin: '0 0 16px',
                      fontSize: 12,
                      fontWeight: 600,
                      color: insufficientCredits ? '#D63B4C' : C.mid,
                    }}
                  >
                    {creditCost} credits required
                    {typeof balance === 'number' ? ` — you have ${balance} credits` : ''}
                    {insufficientCredits ? '. Top up to generate a video.' : ''}
                  </p>
                )}
                {sampleVideosLoading ? (
                  <p style={{ color: C.mid, fontSize: 13 }}>Loading motion templates...</p>
                ) : (sampleVideos?.items.length ?? 0) === 0 ? (
                  <p style={{ color: C.mid, fontSize: 13 }}>No video templates are available.</p>
                ) : (
                  <div className="wizard-step2-grid">
                    {(sampleVideos?.items ?? []).map((option) => {
                      const selected = option.id === sampleVideoId;
                      return (
                        <button
                          key={option.id}
                          type="button"
                          aria-pressed={selected}
                          onClick={() => setSampleVideoId(option.id)}
                          style={{
                            position: 'relative',
                            padding: 0,
                            textAlign: 'left',
                            overflow: 'hidden',
                            border: selected ? `2px solid ${C.pink}` : `1px solid ${C.border}`,
                            borderRadius: 8,
                            background: C.card,
                            cursor: 'pointer',
                          }}
                        >
                          <div
                            style={{
                              position: 'relative',
                              aspectRatio: '9 / 16',
                              background: C.lighter,
                            }}
                          >
                            {/* eslint-disable-next-line @next/next/no-img-element */}
                            {/* biome-ignore lint/performance/noImgElement: animated GIF preview, presigned R2 URL */}
                            <img
                              src={option.thumbnailUrl}
                              alt={option.title}
                              style={{
                                width: '100%',
                                height: '100%',
                                objectFit: 'cover',
                                display: 'block',
                              }}
                            />
                            {selected && (
                              <span
                                style={{
                                  position: 'absolute',
                                  top: 10,
                                  right: 10,
                                  width: 22,
                                  height: 22,
                                  borderRadius: 999,
                                  background: C.pink,
                                  color: C.white,
                                  display: 'grid',
                                  placeItems: 'center',
                                }}
                              >
                                <Check size={14} />
                              </span>
                            )}
                          </div>
                          <span
                            style={{
                              display: 'block',
                              padding: '10px 12px',
                              overflow: 'hidden',
                              textOverflow: 'ellipsis',
                              whiteSpace: 'nowrap',
                              color: C.text,
                              fontSize: 13,
                              fontWeight: 600,
                            }}
                          >
                            {option.title}
                          </span>
                        </button>
                      );
                    })}
                  </div>
                )}
              </>
            )}

            {step === 3 && (
              <div className="wizard-step3-grid">
                <div
                  style={{ border: `1px solid ${C.border}`, borderRadius: 6, overflow: 'hidden' }}
                >
                  <div style={{ aspectRatio: '3 / 4', background: C.lighter }}>
                    {source?.kind === 'existing' && (
                      <JobThumbnail jobId={source.jobId} alt="Selected catalogue" />
                    )}
                    {source?.kind === 'upload' && (
                      // eslint-disable-next-line @next/next/no-img-element
                      // biome-ignore lint/performance/noImgElement: local blob URL preview
                      <img
                        src={source.previewUrl}
                        alt="Selected upload"
                        style={{ width: '100%', height: '100%', objectFit: 'cover' }}
                      />
                    )}
                  </div>
                  <div style={{ padding: 10, color: C.mid, fontSize: 12 }}>
                    {source?.kind === 'upload' ? 'Uploaded image' : 'Catalogue image'}
                  </div>
                </div>
                <div
                  style={{ border: `1px solid ${C.border}`, borderRadius: 6, overflow: 'hidden' }}
                >
                  <div style={{ aspectRatio: '3 / 4', background: C.lighter }}>
                    {selectedSample && (
                      <video
                        src={selectedSample.previewVideoUrl}
                        poster={selectedSample.thumbnailUrl}
                        muted
                        controls
                        style={{
                          width: '100%',
                          height: '100%',
                          objectFit: 'cover',
                          display: 'block',
                        }}
                      />
                    )}
                  </div>
                  <div style={{ padding: 10, color: C.mid, fontSize: 12 }}>
                    {selectedSample?.title ?? 'Motion template'}
                  </div>
                </div>
                {insufficientCredits && (
                  <p style={{ gridColumn: '1 / -1', margin: 0, color: '#D63B4C', fontSize: 13 }}>
                    This video costs {creditCost} credits and you have {balance} credits. Top up to
                    generate this video.
                  </p>
                )}
                {error && (
                  <p style={{ gridColumn: '1 / -1', margin: 0, color: '#D63B4C', fontSize: 13 }}>
                    {error}
                  </p>
                )}
              </div>
            )}
          </div>

          <footer
            style={{
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'space-between',
              gap: 12,
              padding: '16px 20px',
              borderTop: `1px solid ${C.border}`,
            }}
          >
            {step > 1 ? (
              <button
                type="button"
                disabled={submitting}
                onClick={() => setStep((current) => (current - 1) as 1 | 2 | 3)}
                style={{
                  display: 'inline-flex',
                  alignItems: 'center',
                  gap: 6,
                  border: 'none',
                  background: 'transparent',
                  color: C.mid,
                  padding: 8,
                  fontSize: 13,
                  cursor: submitting ? 'not-allowed' : 'pointer',
                }}
              >
                <ChevronLeft size={16} />
                Back
              </button>
            ) : (
              <span />
            )}
            {step < 3 ? (
              <GradBtn
                disabled={nextDisabled}
                onClick={() => setStep((current) => (current + 1) as 1 | 2 | 3)}
              >
                Next
              </GradBtn>
            ) : (
              <Tooltip
                tip={
                  insufficientCredits
                    ? `You need ${creditCost} credits and have ${balance}. Top up to continue.`
                    : undefined
                }
              >
                <GradBtn disabled={submitting || insufficientCredits} onClick={handleSubmit}>
                  {submitting ? 'Starting...' : 'Generate video'}
                </GradBtn>
              </Tooltip>
            )}
          </footer>
        </section>
      </div>
    </>
  );
}
