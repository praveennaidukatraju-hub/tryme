interface CatalogueImageOption {
  jobId: string;
  catalogueId: string;
}

interface SampleVideoOption {
  id: string;
  title: string;
  thumbnailUrl: string;
  previewVideoUrl: string;
}

type CatalogueResponse = Array<{
  catalogueId: string;
  jobs: Array<{ id: string; status: string }>;
}>;

// The two ways a video can be sourced: an existing completed AI Vastra job
// (from the catalogues grid), or a fresh upload of any image the user owns —
// not required to have been generated by AI Vastra at all.
type ImageSource =
  | { kind: 'existing'; jobId: string }
  | { kind: 'upload'; r2Key: string; previewUrl: string };

// `/v1/catalogues` only carries one cover thumbnail per catalogue (correct for
// the catalogue grid, which shows one card per catalogue) — a catalogue with
// several completed pose jobs has no per-job thumbnail there. Fetch each job's
// own thumbnail directly, same as the catalogue detail page's ImageCard, so
// every option in this picker shows its own generated image instead of all
// jobs from one catalogue displaying that catalogue's single cover photo.
function JobThumbnail({ jobId, alt }: { jobId: string; alt: string }): React.ReactElement {
  const { data } = useQuery<{ url: string }>({
    queryKey: ['job-thumb', jobId],
    queryFn: () => api.get(`/v1/jobs/${jobId}/thumbnail`),
    staleTime: 55 * 60 * 1000,
  });

  if (!data?.url) {
    return <span style={{ color: C.mid, fontSize: 12 }}>Image unavailable</span>;
  }
  return (
    // eslint-disable-next-line @next/next/no-img-element
    // biome-ignore lint/performance/noImgElement: presigned R2 URL
    <img src={data.url} alt={alt} style={{ width: '100%', height: '100%', objectFit: 'cover' }} />
  );
}

// Click-to-browse or drag-and-drop upload, mirroring Studio's garment upload
// (handleGarmentUpload in apps/(app)/studio/page.tsx): magic-byte validation,
// 10MB soft cap, local blob-URL preview before the network round trip. Fixed
// aspect ratio across every state (idle/uploading/filled) so picking a file
// doesn't reflow the layout next to it.
function UploadDropzone({
  onFile,
  onRemove,
  uploading,
  progress,
  error,
  previewUrl,
}: {
  onFile: (file: File) => void;
  onRemove: () => void;
  uploading: boolean;
  progress: number;
  error: string | null;
  previewUrl: string | null;
}): React.ReactElement {
  const [dragOver, setDragOver] = useState(false);

  return (
    <div style={{ flex: '0 1 300px', minWidth: 220 }}>
      {/* A <label> wrapping the file input is natively keyboard-accessible
          (click or Enter/Space on the label activates the input) — same
          pattern as Studio's garment upload zones. No custom onClick/onKeyDown
          needed, unlike a plain <div>. */}
      <label
        onDragOver={(event) => {
          event.preventDefault();
          if (!uploading) setDragOver(true);
        }}
        onDragLeave={() => setDragOver(false)}
        onDrop={(event) => {
          event.preventDefault();
          setDragOver(false);
          const file = event.dataTransfer.files?.[0];
          if (file && !uploading) onFile(file);
        }}
        style={{
          position: 'relative',
          aspectRatio: '3 / 4',
          overflow: 'hidden',
          border: previewUrl
            ? `1px solid ${C.border}`
            : `2px dashed ${dragOver ? C.pink : C.border}`,
          borderRadius: 12,
          background: previewUrl ? C.lighter : dragOver ? 'rgba(245,92,122,0.04)' : C.lighter,
          cursor: uploading ? 'not-allowed' : 'pointer',
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'center',
          transition: 'background 150ms ease, border-color 150ms ease',
        }}
      >
        <input
          type="file"
          disabled={uploading}
          accept="image/jpeg,image/png,image/webp"
          style={{ display: 'none' }}
          onChange={(event) => {
            const file = event.target.files?.[0];
            event.target.value = '';
            if (file) onFile(file);
          }}
        />
        {previewUrl ? (
          <>
            {/* eslint-disable-next-line @next/next/no-img-element */}
            {/* biome-ignore lint/performance/noImgElement: local blob URL preview */}
            <img
              src={previewUrl}
              alt="Uploaded"
              style={{ width: '100%', height: '100%', objectFit: 'cover' }}
            />
            <button
              type="button"
              aria-label="Remove uploaded image"
              onClick={(event) => {
                event.preventDefault();
                event.stopPropagation();
                onRemove();
              }}
              style={{
                position: 'absolute',
                top: 10,
                right: 10,
                width: 28,
                height: 28,
                borderRadius: '50%',
                background: 'rgba(0,0,0,0.55)',
                border: 'none',
                color: C.white,
                cursor: 'pointer',
                display: 'grid',
                placeItems: 'center',
              }}
            >
              <X size={14} />
            </button>
          </>
        ) : uploading ? (
          <div
            style={{
              display: 'flex',
              flexDirection: 'column',
              alignItems: 'center',
              gap: 12,
              padding: 20,
              width: '100%',
              boxSizing: 'border-box',
            }}
          >
            <div
              style={{
                width: 44,
                height: 44,
                borderRadius: '50%',
                border: `1px solid ${C.border}`,
                display: 'grid',
                placeItems: 'center',
                color: C.pink,
              }}
            >
              <Upload size={20} />
            </div>
            <div style={{ fontSize: 13, fontWeight: 600, color: C.text }}>
              Uploading… {progress}%
            </div>
            <div
              style={{
                width: '80%',
                height: 4,
                borderRadius: 2,
                background: C.border,
                overflow: 'hidden',
              }}
            >
              <div
                style={{
                  width: `${progress}%`,
                  height: '100%',
                  background: grad,
                  transition: 'width 150ms ease',
                }}
              />
            </div>
          </div>
        ) : (
          <div
            style={{
              display: 'flex',
              flexDirection: 'column',
              alignItems: 'center',
              gap: 14,
              padding: 20,
              textAlign: 'center',
            }}
          >
            <div
              style={{
                width: 56,
                height: 56,
                borderRadius: '50%',
                background: dragOver ? 'rgba(245,92,122,0.12)' : C.card,
                border: `1px solid ${dragOver ? C.pink : C.border}`,
                display: 'grid',
                placeItems: 'center',
                color: dragOver ? C.pink : C.mid,
                transition: 'background 150ms ease, border-color 150ms ease, color 150ms ease',
              }}
            >
              <Upload size={24} />
            </div>
            <div style={{ fontSize: 15, fontWeight: 700, color: C.text }}>
              Click or drag an image here
            </div>
            <div style={{ fontSize: 12, color: C.mid, lineHeight: 1.5 }}>
              JPEG, PNG, or WebP · up to 10MB
            </div>
          </div>
        )}
      </label>
      {previewUrl && !error && (
        <p style={{ margin: '8px 0 0', color: C.mid, fontSize: 12 }}>
          Looks good — click the × to choose a different photo.
        </p>
      )}
      {error && <p style={{ margin: '8px 0 0', color: '#D63B4C', fontSize: 12 }}>{error}</p>}
    </div>
  );
}

